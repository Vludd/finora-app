export type ThemePaletteId = (typeof THEME_PALETTES)[number]["id"];

export const DEFAULT_THEME_PALETTE_ID: ThemePaletteId = "emerald";

export function isThemePaletteId(
  value: string | null | undefined,
): value is ThemePaletteId {
  return THEME_PALETTES.some((palette) => palette.id === value);
}

export function getThemePalette(id: ThemePaletteId) {
  return (
    THEME_PALETTES.find((palette) => palette.id === id) ?? THEME_PALETTES[0]
  );
}
