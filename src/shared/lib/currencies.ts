export type CurrencyCode = (typeof CURRENCIES)[number]["code"];
export type CurrencyDefinition = (typeof CURRENCIES)[number];

export const DEFAULT_CURRENCY_CODE: CurrencyCode = "KZT";

export const DEFAULT_CURRENCY: CurrencyDefinition =
  CURRENCIES.find((currency) => currency.code === DEFAULT_CURRENCY_CODE) ??
  CURRENCIES[0];

export function isCurrencyCode(
  value: string | null | undefined,
): value is CurrencyCode {
  return CURRENCIES.some((currency) => currency.code === value);
}

export function getCurrencyByCode(
  code: CurrencyCode | string,
): CurrencyDefinition {
  return (
    CURRENCIES.find((currency) => currency.code === code) ?? DEFAULT_CURRENCY
  );
}
